# gen_atan_table.py -- writes f80_atan_table.inc (the FPATAN fast path's constants, f80.cpp): python3 gen_atan_table.py
# floor(atan(k/256) * 2^128) for k = 0..256, floor(pi/2 * 2^126), floor(pi * 2^126), floor(2^127/(2n+1)).
from fractions import Fraction
W = 520
ONE = 1 << W
def atan_fix(num, den):  # atan(num/den) * 2^W, 0 <= num/den <= 1, Euler series, truncation error < 2^-W * (#terms)
    if num == 0: return 0
    # y = x^2/(1+x^2) = num^2/(num^2+den^2); atan x = x/(1+x^2) * sum_{n>=0} (2n)!!/(2n+1)!! y^n
    N2, D2 = num * num, num * num + den * den
    term = (num * den * ONE) // D2   # x/(1+x^2) = num*den/(num^2+den^2)
    s = term; n = 1
    while term:
        term = term * N2 * (2 * n) // (D2 * (2 * n + 1)); s += term; n += 1
    return s
def machin_pi():
    def acot(x):
        s = t = ONE // x; x2 = x * x; n = 1; sign = -1
        while t:
            t //= x2; s += sign * (t // (2 * n + 1)); sign = -sign; n += 1
        return s
    return 4 * (4 * acot(5) - acot(239))
pi = machin_pi()
assert abs(4 * atan_fix(1, 1) - pi) < 1 << 20, "pi check"
out = []
out.append("// generated by gen_atan_table.py: floor(atan(k/256) * 2^128), k = 0..256, as {hi, lo}")
out.append("const uint64_t kAtanTab[257][2] = {")
for k in range(257):
    v = atan_fix(k, 256) >> (W - 128)
    if k == 256: v = min(v, (1 << 128) - 1)
    out.append("  {0x%016xULL, 0x%016xULL}," % (v >> 64, v & ((1 << 64) - 1)))
out.append("};")
hp = (pi // 2) >> (W - 126); p = pi >> (W - 126)
out.append("const uint64_t kHalfPi126[2] = {0x%016xULL, 0x%016xULL};  // floor(pi/2 * 2^126)" % (hp >> 64, hp & ((1 << 64) - 1)))
out.append("const uint64_t kPi126[2] = {0x%016xULL, 0x%016xULL};      // floor(pi * 2^126)" % (p >> 64, p & ((1 << 64) - 1)))
out.append("const uint64_t kInvOdd127[8][2] = {  // floor(2^127 / (2n+1)), n = 0..7")
for n in range(8):
    v = min((1 << 127) // (2 * n + 1), (1 << 127))
    out.append("  {0x%016xULL, 0x%016xULL}," % (v >> 64, v & ((1 << 64) - 1)))
out.append("};")
import os
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "f80_atan_table.inc"), "w").write("\n".join(out) + "\n")
# self-check: identity atan(a)+atan(b) = atan((a+b)/(1-ab)) for a few, at W bits
for k in (1, 37, 128, 200):
    a = atan_fix(k, 256); b = atan_fix(1, 7)
    # (k/256 + 1/7)/(1 - k/1792) = (7k+256)/(1792-k)
    num, den = 7 * k + 256, 1792 - k
    if num <= den: c = atan_fix(num, den)
    else: c = pi // 2 - atan_fix(den, num)
    assert abs(a + b - c) < 1 << 24, k
print("ok", hex(atan_fix(256, 256) >> (W - 128)))
