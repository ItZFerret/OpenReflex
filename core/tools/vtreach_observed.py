#!/usr/bin/env python3
"""vtreach_observed.py -- the runtime evidence for sigcheck_vt.reach_pass (w-vtunported): which vtable targets each product function's slot
calls were seen to reach in RX_FN_TRACE runs (core/tools/vtrace_build.sh + vtrace_run.py, the w-vtlog tooling).

Why. A slot call with a generic receiver (`obj`, `p`, a wrapper argument) says nothing about the receiver's class in the C text. One observed
target settles it: the virtual at slot k is declared by one class of the receiver's static type chain (the "introducer", the root-most base
with more than k slots), so every class that can reach the call is a subclass of that introducer. reach_pass narrows a generic site to the
constructed classes whose introducer at the slot is one of the introducers of the targets observed for that site's function.

usage:  vtreach_observed.py <out.tsv> <trace file>... --lib <traced image> [--lib ...] --static <static.json>
Output: one line per (file, function) that holds a traced call: file TAB function TAB the vtable targets its calls reached (comma list). A
record is credited to the function that converted the address and, when that is one of the typed wrappers of the static sites (loop_tc1,
vcall0, anim_vcall0 ...: --static) or a header helper, to the frames above it up to the first function that is neither (the caller that passed
the slot).
Frames come from atos (inline frames included) on the five return addresses a record keeps.
The table is checked in as core/tools/vtreach_observed.tsv; regenerate it from fresh runs when the code moves (see core/plan/QUEUE.md
w-vtunported): trace a build with core/tools/vtrace_build.sh, run vtrace_run.py sets a / b / c (plus the w-vtlog drivers), then this script
with --static from `sigcheck.py --vt-dump=<static.json>`, and merge the old table in (function names are stable across line edits)."""
import os, sys, csv, json, collections, argparse

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from vtrace_check import resolve_frames


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("traces", nargs="+")
    ap.add_argument("--lib", action="append", required=True)
    ap.add_argument("--static", required=True, help="sigcheck.py --vt-dump output: the typed wrappers (loop_tc1, vcall0, ...) of the call sites")
    a = ap.parse_args()
    recs = collections.defaultdict(set)     # return-address tuple -> targets
    for tf in a.traces:
        for ln in open(tf, encoding="utf-8", errors="replace"):
            f = ln.rstrip("\n").split("\t")
            if len(f) < 5:
                continue
            try:
                t = int(f[2], 16)
            except ValueError:
                continue
            recs[tuple(f[3].split(","))].add(t)
    frames = resolve_frames({x for ras in recs for x in ras}, a.lib)
    vt = {int(r["target"], 16) for r in csv.DictReader(open(os.path.join(HERE, "..", "..", "_re/out/vtables.tsv"), encoding="latin-1"), delimiter="\t")}
    wrappers = {w for st in json.load(open(a.static))["sites"] for w in st["chain"]}
    seen = collections.defaultdict(set)     # (file, function) -> targets
    for ras, ts in recs.items():
        ts = ts & vt                          # only vtable targets matter (the slot narrowing)
        if not ts:
            continue
        done = False
        for x in ras:
            for (fn, fl, _l) in frames.get(x, []):
                seen[(os.path.basename(fl), fn)] |= ts
                if fn not in wrappers and not fl.endswith(".h"):   # the function that holds the call site (past the wrappers and the header
                    # helpers they go through: act_call_fn, rr_vcall ...): its callers are not credited
                    done = True
                    break
            if done:
                break
    with open(a.out, "w") as o:
        o.write("# vtreach_observed.tsv -- generated by core/tools/vtreach_observed.py from RX_FN_TRACE runs (see its docstring); file TAB function TAB targets\n")
        for (fl, fn) in sorted(seen):
            o.write("%s\t%s\t%s\n" % (fl, fn, ",".join("%08x" % t for t in sorted(seen[(fl, fn)]))))
    print("%d records, %d functions with observed targets" % (len(recs), len(seen)))


if __name__ == "__main__":
    main()
