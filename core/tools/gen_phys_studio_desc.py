#!/usr/bin/env python3
"""gen_phys_studio_desc.py -- writes core/game/phys_studio_desc.inc from core/tools/phys_studio_desc.txt: the PHYSICS STUDIO labels,
descriptions, units and natural bounds of every distinct vehicle parameter name (game/phys_studio.c: unit_of, set_bounds and the
catalog's N lines; the client reads the N lines). Checks that every registered name (phys_studio_names.inc) has exactly one entry.
Rerun after the text or the names change:
  python3 core/tools/gen_phys_studio_desc.py"""
import os, re, sys
T = os.path.dirname(os.path.abspath(__file__))
G = os.path.join(T, "..", "game")
src = os.path.join(T, "phys_studio_desc.txt")
names = []
for m in re.finditer(r"k_ps_names_\w+\[\d+\] = \{(.*?)\};", open(os.path.join(G, "phys_studio_names.inc")).read(), re.S):
    for n in re.findall(r'"([^"]+)"', m.group(1)):
        if n not in names: names.append(n)
rows = {}
for ln, line in enumerate(open(src, encoding="utf-8"), 1):
    if not line.strip() or line.startswith("#"): continue
    f = [x.strip() for x in line.rstrip("\n").split(" | ")]
    if len(f) != 6: sys.exit("%s:%d: %d fields, want 6" % (src, ln, len(f)))
    name, label, unit, unit_x, bounds, desc = f
    if name in rows: sys.exit("%s:%d: %s twice" % (src, ln, name))
    if name not in names: sys.exit("%s:%d: %s is not a registered name" % (src, ln, name))
    for s in (label, unit, unit_x, desc):
        if "\t" in s or '"' in s or "\\" in s: sys.exit("%s:%d: tab / quote / backslash in a field" % (src, ln))
    if len(desc) > 300 or len(label) > 60: sys.exit("%s:%d: too long" % (src, ln))
    lo_t = hi_t = 0; lo_v = hi_v = 0.0; toggle = 0
    if bounds != "-":
        for tok in bounds.split():
            if tok == "toggle": toggle = 1; lo_t = hi_t = 2; lo_v = 0.0; hi_v = 1.0; continue
            m = re.fullmatch(r"(lo|hi)=(-?[0-9.]+)(x?)", tok)
            if not m: sys.exit("%s:%d: bad bounds token %r" % (src, ln, tok))
            t = 1 if m.group(3) else 2; v = float(m.group(2))
            if m.group(1) == "lo": lo_t, lo_v = t, v
            else: hi_t, hi_v = t, v
    rows[name] = (label, unit, unit_x, desc, lo_t, lo_v, hi_t, hi_v, toggle)
missing = [n for n in names if n not in rows]
if missing: sys.exit("no entry for: " + ", ".join(missing))
def cs(s): return '"%s"' % s
def fl(v):
    s = "%.6g" % v
    return s + "f" if ("." in s or "e" in s) else s + ".0f"
out = ["/* phys_studio_desc.inc -- generated by core/tools/gen_phys_studio_desc.py from core/tools/phys_studio_desc.txt; do not edit.",
       " * {name, label, unit (a curve: its y), unit of a curve's x, description, lo kind, lo, hi kind, hi, toggle}; kind 0 = the generic bound,",
       " * 1 = a multiple of the file's (positive) value, 2 = absolute. */",
       "typedef struct { const char *name, *label, *unit, *unit_x, *desc; uint8_t lo_t, hi_t, toggle; float lo_v, hi_v; } ps_desc;",
       "static const ps_desc k_ps_desc[%d] = {" % len(names)]
for n in names:
    label, unit, unit_x, desc, lo_t, lo_v, hi_t, hi_v, tg = rows[n]
    u = "" if unit == "-" else unit
    ux = "" if unit_x == "-" else unit_x
    out.append("    {%s, %s, %s, %s, %s, %d, %d, %d, %s, %s}," % (cs(n), cs(label), cs(u), cs(ux), cs(desc), lo_t, hi_t, tg, fl(lo_v), fl(hi_v)))
out.append("};")
open(os.path.join(G, "phys_studio_desc.inc"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print("wrote phys_studio_desc.inc: %d names, %d with bounds, %d unit (unknown), %d described as no known effect" %
      (len(names), sum(1 for r in rows.values() if r[4] or r[6]), sum(1 for r in rows.values() if r[1] == "(unknown)"),
       sum(1 for r in rows.values() if "no known effect" in r[3])))
