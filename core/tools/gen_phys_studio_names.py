#!/usr/bin/env python3
"""gen_phys_studio_names.py -- writes core/game/phys_studio_names.inc: the registered parameter names of the four registration tables
(build_vehicle_params.inc / _atv_ / _utv_ / _bt_), in table order, as host strings for the PHYSICS STUDIO catalog (game/phys_studio.c).
The tables name their .rdata strings by address; the name is the comment after each record. Rerun after a table changes:
  python3 core/tools/gen_phys_studio_names.py"""
import os, re
G = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "game")
out = ["/* phys_studio_names.inc -- generated by core/tools/gen_phys_studio_names.py from the registration tables; do not edit. */"]
for tag, f in (("moto", "build_vehicle_params.inc"), ("atv", "build_vehicle_atv_params.inc"), ("utv", "build_vehicle_utv_params.inc"), ("bt", "build_vehicle_bt_params.inc")):
    names = re.findall(r"\{0x[0-9a-f]+, \d, 0x[0-9a-f]+, \{[^}]*\}\},\s*/\* (\w+) \*/", open(os.path.join(G, f)).read())
    out.append("static const char* const k_ps_names_%s[%d] = {" % (tag, len(names)))
    for i in range(0, len(names), 4): out.append("    " + " ".join('"%s",' % n for n in names[i:i + 4]))
    out.append("};")
open(os.path.join(G, "phys_studio_names.inc"), "w").write("\n".join(out) + "\n")
print("wrote phys_studio_names.inc")
