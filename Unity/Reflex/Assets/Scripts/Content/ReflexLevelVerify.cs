        public static string VerifyConcordScenery(ReflexLevelContent c)
        {
            var sb = new StringBuilder();
            string dir = Path.Combine(OutDir, "unity_concord/scenery");
            var doc = JObject.Parse(File.ReadAllText(Path.Combine(dir, "ConcordScenery.json")));
            var models = (JObject)doc["models"]; var insts = (JArray)doc["instances"]; var mats = (JObject)doc["materials"];
            sb.AppendLine($"models: python {models.Count}, C# {c.sceneModels.Count}; instances: python {insts.Count}, C# {c.instances.Count}; materials: python {mats.Count}, C# {c.sceneMaterials.Count}");
            var pos = new Stat { name = "model positions (python rounds to 5 decimals)" }; var nor = new Stat { name = "model normals" };
            var uv = new Stat { name = "model uv (u, 1 - v)" }; var tri = new Stat { name = "triangle indices (exact)" };
            var cnt = new Stat { name = "vertex/submesh counts (exact)" };
            foreach (var kv in models)
            {
                if (!c.sceneModels.TryGetValue(kv.Key, out var m)) { cnt.Add(1, 0, "missing model " + kv.Key); continue; }
                var p = (JArray)kv.Value["positions"]; var n = (JArray)kv.Value["normals"]; var u = (JArray)kv.Value["uvs"]; var subs = (JArray)kv.Value["submeshes"];
                cnt.Add(Math.Abs(m.positions.Length * 3 - p.Count), 0, kv.Key + " vertices");
                cnt.Add(Math.Abs(m.triangles.Count - subs.Count), 0, kv.Key + " submeshes");
                int vn = Math.Min(m.positions.Length, p.Count / 3);
                for (int i = 0; i < vn; i++)
                {
                    pos.Add(Math.Abs(m.positions[i].x - F(p[3 * i])), 1e-4, $"{kv.Key} v{i}"); pos.Add(Math.Abs(m.positions[i].y - F(p[3 * i + 1])), 1e-4, $"{kv.Key} v{i}"); pos.Add(Math.Abs(m.positions[i].z - F(p[3 * i + 2])), 1e-4, $"{kv.Key} v{i}");
                    nor.Add(Math.Abs(m.normals[i].x - F(n[3 * i])), 2e-4, $"{kv.Key} v{i}"); nor.Add(Math.Abs(m.normals[i].y - F(n[3 * i + 1])), 2e-4, $"{kv.Key} v{i}"); nor.Add(Math.Abs(m.normals[i].z - F(n[3 * i + 2])), 2e-4, $"{kv.Key} v{i}");
                    uv.Add(Math.Abs(m.uv0[i].x - F(u[2 * i])), 2e-5, $"{kv.Key} v{i}"); uv.Add(Math.Abs(m.uv0[i].y - (1 - F(u[2 * i + 1]))), 2e-5, $"{kv.Key} v{i}");
                }
                for (int s = 0; s < Math.Min(subs.Count, m.triangles.Count); s++)
                {
                    var pt = ((JArray)subs[s]["triangles"]).Select(x => (int)x).ToArray();
                    bool same = pt.SequenceEqual(m.triangles[s]);
                    tri.Add(same ? 0 : 1, 0, $"{kv.Key} submesh {s}: python {pt.Length} indices, C# {m.triangles[s].Length}");
                    cnt.Add(((string)subs[s]["material"] == m.bindingMaterials[s]) ? 0 : 1, 0, kv.Key + " binding material " + s);
                }
            }
            foreach (var s in new[] { cnt, pos, nor, uv, tri }) sb.AppendLine("  " + s);

            // instances
            var im = new Stat { name = "instance matrices (exact)" }; var ib = new Stat { name = "instance entity/name/model/group/materials (exact)" };
            int ni = Math.Min(insts.Count, c.instances.Count);
            for (int i = 0; i < ni; i++)
            {
                var pi = insts[i]; var ci = c.instances[i];
                var pm = Floats(pi["matrix"]);
                for (int k = 0; k < 16; k++) im.Add(Math.Abs(pm[k] - ci.matrix[k]), 0, $"instance {i} m{k}");
                bool same = (int)pi["entity_id"] == ci.entityId && (string)pi["name"] == ci.name && (string)pi["model"] == ci.model && (string)pi["group"] == ci.group
                            && ((JArray)pi["materials"]).Select(x => (string)x).SequenceEqual(ci.materials);
                ib.Add(same ? 0 : 1, 0, $"instance {i} {(string)pi["name"]} / {ci.name}");
            }
            sb.AppendLine("  " + im); sb.AppendLine("  " + ib);

            // materials
            var ms = new Stat { name = "material pixel shader / textures / cull / alpha test, blend, ref (exact)" };
            foreach (var kv in mats)
            {
                if (!c.sceneMaterials.TryGetValue(kv.Key, out var m)) { ms.Add(1, 0, "missing material " + kv.Key); continue; }
                var v = kv.Value;
                bool same = (string)v["pixel_shader"] == m.pixelShader && ((JArray)v["textures"]).Select(x => (string)x).SequenceEqual(m.textures)
                            && (int)v["cull_mode"] == m.cull && (bool)v["alpha_test"] == m.alphaTest && (bool)v["alpha_blend"] == m.alphaBlend && (int)v["alpha_ref"] == m.alphaRef;
                ms.Add(same ? 0 : 1, 0, kv.Key);
            }
            sb.AppendLine("  " + ms);

            // texture pixels (python PNG = the diffuse picked by its own heuristic)
            var trgb = new Stat { name = "texture RGB vs PNG (exact)" }; var talpha = new Stat { name = "texture alpha vs PNG (exact)" };
            int ntex = 0;
            foreach (var png in Directory.GetFiles(Path.Combine(dir, "textures"), "*.png"))
            {
                string name = Path.GetFileNameWithoutExtension(png);
                if (c.HasAsset(name, "texture")) { CompareTexture(c, trgb, talpha, name, png, name); ntex++; }
            }
            sb.AppendLine($"  textures compared: {ntex}"); sb.AppendLine("  " + trgb); sb.AppendLine("  " + talpha);
            return sb.ToString();
        }

