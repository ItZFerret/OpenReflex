        static Vector3 Xf(Vector3 v, float[] m) => new Vector3(v.x * m[0] + v.y * m[4] + v.z * m[8] + m[12], v.x * m[1] + v.y * m[5] + v.z * m[9] + m[13], v.x * m[2] + v.y * m[6] + v.z * m[10] + m[14]);
        static Vector3 XfN(Vector3 v, float[] m) => new Vector3(v.x * m[0] + v.y * m[4] + v.z * m[8], v.x * m[1] + v.y * m[5] + v.z * m[9], v.x * m[2] + v.y * m[6] + v.z * m[10]);

        /// World-space meshes of the Python exports (alpine_scenery_export, start_support_export) against model x instance matrix.
        public static string VerifyWorldMeshes(ReflexLevelContent c, string jsonPath, string title)
        {
            var sb = new StringBuilder();
            var doc = JObject.Parse(File.ReadAllText(jsonPath));
            var pos = new Stat { name = "world positions" }; var nor = new Stat { name = "world normals" }; var uv = new Stat { name = "uv0" };
            var tri = new Stat { name = "triangles (exact)" }; var uv2 = new Stat { name = "uv1" }; var col = new Stat { name = "vertex colours (rgba)" };
            int found = 0;
            foreach (var mesh in (JArray)doc["meshes"])
            {
                string model = (string)mesh["source_model"] ?? ((string)mesh["name"]).Substring(((string)mesh["name"]).IndexOf('_') + 1);
                JToken idTok = mesh["source_scene_entity_id"] ?? doc["source_scene_entity_id"];
                int id = (int)idTok;
                var inst = c.instances.FirstOrDefault(i => i.entityId == id);
                if (inst == null || !c.sceneModels.TryGetValue(inst.model, out var m)) { tri.Add(1, 0, "missing instance " + id); continue; }
                found++;
                // python meshes are per LOD0 binding of the entity; locate the binding by material + surface triangles
                var p = (JArray)mesh["positions"]; var n = (JArray)mesh["normals"]; var uv0 = (JArray)mesh["uvs"];
                int sub = -1;
                for (int s = 0; s < m.triangles.Count; s++)
                {
                    int first = m.triangles[s].Length > 0 ? m.triangles[s].Min() : 0;
                    int count = m.triangles[s].Length > 0 ? m.triangles[s].Max() - first + 1 : 0;
                    if (count == p.Count && m.bindingMaterials[s] == (string)mesh["material"]) { sub = s; break; }
                }
                if (sub < 0) { tri.Add(1, 0, $"entity {id} {model}: no binding with {p.Count} vertices"); continue; }
                int off = m.triangles[sub].Min();
                var matrix = inst.matrix;
                for (int i = 0; i < p.Count; i++)
                {
                    Compare(pos, Xf(m.positions[off + i], matrix), p[i], 1e-3, $"{model} v{i}");
                    Compare(nor, XfN(m.normals[off + i], matrix), n[i], 2e-4, $"{model} v{i}");
                    uv.Add(Math.Abs(m.uv0[off + i].x - F(uv0[i][0])), 2e-3, $"{model} v{i}"); uv.Add(Math.Abs(m.uv0[off + i].y - (1 - F(uv0[i][1]))), 2e-3, $"{model} v{i}");
                    if (mesh["uv2"] is JArray u2) { uv2.Add(Math.Abs(m.uv1[off + i].x - F(u2[i][0])), 2e-3, $"{model} v{i}"); uv2.Add(Math.Abs(m.uv1[off + i].y - (1 - F(u2[i][1]))), 2e-3, $"{model} v{i}"); }
                    if (mesh["colors"] is JArray cc && m.colors != null)
                    {
                        col.Add(Math.Abs(m.colors[off + i].r / 255f - F(cc[i][0])), 1e-3, $"{model} v{i}"); col.Add(Math.Abs(m.colors[off + i].g / 255f - F(cc[i][1])), 1e-3, $"{model} v{i}");
                        col.Add(Math.Abs(m.colors[off + i].b / 255f - F(cc[i][2])), 1e-3, $"{model} v{i}"); col.Add(Math.Abs(m.colors[off + i].a / 255f - F(cc[i][3])), 1e-3, $"{model} v{i}");
                    }
                }
                var pt = Tri(mesh["triangles"]); var mine = m.triangles[sub].Select(t => t - off).ToArray();
                tri.Add(pt.SequenceEqual(mine) ? 0 : 1, 0, $"{model} triangles: python {pt.Length}, C# {mine.Length}");
            }
            sb.AppendLine($"{title}: {found}/{((JArray)doc["meshes"]).Count} python meshes located in the C# instances");
            foreach (var s in new[] { pos, nor, uv, uv2, col, tri }) if (s.n > 0) sb.AppendLine("  " + s);
            return sb.ToString();
        }

