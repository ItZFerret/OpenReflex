        public static string VerifyTerrain(ReflexLevelContent c, string levelDir, string prefix)
        {
            var sb = new StringBuilder();
            var contract = JObject.Parse(File.ReadAllText(Path.Combine(OutDir, levelDir, "terrain_textures/terrain-shader.json")));
            var ti = c.terrainData;
            var diff = new Stat { name = "contract values (names, sampler states, parameters, lighting, fog, spacing)" };
            diff.Add(ti.materialName == (string)contract["material"] ? 0 : 1, 0, "material " + ti.materialName);
            diff.Add(ti.spacing == (int)contract["spacing"] ? 0 : 1, 0, "spacing");
            var slots = (JArray)contract["slots"];
            for (int i = 0; i < slots.Count; i++)
            {
                diff.Add((string)slots[i]["texture"] == ti.material.textures[i] ? 0 : 1, 0, "slot " + i + " texture");
                var st = (JObject)slots[i]["sampler_states"];
                var mine = ti.material.samplerStates[i];
                foreach (var kv in st) { float v = (float)kv.Value; int key = kv.Key == "MINFILTER" ? 6 : kv.Key == "MAGFILTER" ? 5 : kv.Key == "MIPFILTER" ? 7 : kv.Key == "ADDRESSU" ? 1 : kv.Key == "ADDRESSV" ? 2 : kv.Key == "ADDRESSW" ? 3 : 8;
                    diff.Add(mine.TryGetValue(key, out var mv) ? Math.Abs(mv - v) : 1, 0, $"slot {i} {kv.Key}"); }
            }
            foreach (var kv in (JObject)contract["parameters"])
            {
                var pv = Floats(kv.Value["value"]); var mv = ti.material.parameters[kv.Key];
                for (int k = 0; k < 4; k++) diff.Add(Math.Abs(pv[k] - mv[k]), 0, kv.Key);
            }
            var light = contract["lighting"];
            var sd = Floats(light["gSunLight_direction_to_sun"]); var sc = Floats(light["gSunLightColor"]);
            for (int k = 0; k < 3; k++) { diff.Add(Math.Abs(sd[k] - c.lighting.sunDirection[k]), 1e-6, "sun dir"); diff.Add(Math.Abs(sc[k] - c.lighting.sunColor[k]), 1e-6, "sun colour"); }
            var fog = contract["fog"];
            var fs = Floats(fog["ColorStart"]); var fe = Floats(fog["ColorEnd"]);
            for (int k = 0; k < 3; k++) { diff.Add(Math.Abs(fs[k] - c.lighting.fogColorStart[k]), 0, "fog start"); diff.Add(Math.Abs(fe[k] - c.lighting.fogColorEnd[k]), 0, "fog end"); }
            diff.Add(Math.Abs(F(fog["AmountStart"]) - c.lighting.fogAmountStart) + Math.Abs(F(fog["AmountEnd"]) - c.lighting.fogAmountEnd)
                     + Math.Abs(F(fog["DistanceStart"]) - c.lighting.fogDistanceStart) + Math.Abs(F(fog["DistanceEnd"]) - c.lighting.fogDistanceEnd), 0, "fog scalars");
            sb.AppendLine("  " + diff);

            var trgb = new Stat { name = "terrain texture RGB vs PNG (exact)" }; var talpha = new Stat { name = "terrain texture alpha vs PNG" };
            foreach (var name in ti.material.textures.Distinct())
                CompareTexture(c, trgb, talpha, name, Path.Combine(OutDir, levelDir, "terrain_textures", name + ".png"), name);
            sb.AppendLine("  " + trgb); sb.AppendLine("  " + talpha);

            // shadow visibility
            var vis = new Stat { name = "shadow visibility bytes vs PNG (exact)" };
            string vpng = Path.Combine(OutDir, levelDir, "terrain_textures", prefix + "_TerrainShadowVis.png");
            if (File.Exists(vpng) && ti.shadowVis != null)
            {
                var raw = LoadPng(vpng, out int w, out int h);
                for (int y = 0; y < h; y++) for (int x = 0; x < w; x++) vis.Add(Math.Abs(ti.shadowVis[y * w + x] - raw[((h - 1 - y) * w + x) * 4]), 0, $"({x},{y})");
            }
            sb.AppendLine("  " + vis);

            // tracks
            var tr = new Stat { name = "track texture RGBA vs PNG (exact)" }; var tra = new Stat { name = "track alpha" };
            string db = c.level;
            foreach (var png in Directory.GetFiles(Path.Combine(OutDir, "unity_assets/tracks"), db + ".*.png"))
            {
                string name = Path.GetFileNameWithoutExtension(png).Substring(db.Length + 1);
                if (ti.trackNames.Contains(name)) CompareTexture(c, tr, tra, name, png, "track " + name);
            }
            sb.AppendLine("  " + tr); sb.AppendLine("  " + tra);
            return sb.ToString();
        }

        public static string VerifyAnchors(ReflexLevelContent c, string levelDir)
        {
            var arr = JArray.Parse(File.ReadAllText(Path.Combine(OutDir, levelDir, "spawn_anchors.json")));
            var st = new Stat { name = "spawn anchors (entity id, index, name, matrix exact)" };
            st.Add(arr.Count == c.anchors.Count ? 0 : 1, 0, $"count {arr.Count} vs {c.anchors.Count}");
            for (int i = 0; i < Math.Min(arr.Count, c.anchors.Count); i++)
            {
                st.Add((int)arr[i]["entity_id"] == c.anchors[i].entityId && (int)arr[i]["index"] == c.anchors[i].index && (string)arr[i]["name"] == c.anchors[i].name ? 0 : 1, 0, "anchor " + i);
                var m = Floats(arr[i]["matrix"]);
                for (int k = 0; k < 16; k++) st.Add(Math.Abs(m[k] - c.anchors[i].matrix[k]), 0, $"anchor {i} m{k}");
            }
            return "  " + st + "\n";
        }
