        sealed class Stat
        {
            public string name; public double maxDiff; public long n, bad; public string first = "";
            public void Add(double d, double tol, string where)
            {
                n++; if (d > maxDiff) maxDiff = d;
                if (d > tol) { bad++; if (first.Length == 0) first = where; }
            }
            public override string ToString() => $"{name}: {n} values, max diff {maxDiff:G3}, {bad} beyond tolerance{(bad > 0 ? " (first: " + first + ")" : "")}";
        }

        public static void UsePythonDxt5Alpha(bool on) { ReflexTex.PythonDxt5Alpha = on; }
        /// Height map of the level's terrain entity (raw R32F, D3D row order) for test scenes.
        public static float[] ReadHeights(ReflexLevelContent c, out int size)
        {
            var raw = c.ReadAsset(c.terrainData.heightName, "texture");
            var h = ReflexTex.ReadR32F(raw, out size, out _);
            return h;
        }
        /// The derived fill-light rig (ReflexLevelContent.LightDirections) against the light's own baked spherical light map
        /// (AmbientDirectionalLightRSData.SphericalLightMap, generated by ps_spherical_light from the same four lights): rgb = sum sat(N.L_i) C_i.
        public static string VerifyLightRig(ReflexLevelContent c)
        {
            var l = c.lighting;
            if (string.IsNullOrEmpty(l.sphericalLightMap) || !c.HasAsset(l.sphericalLightMap, "texture")) return "  light rig: no baked spherical light map to compare\n";
            var px = ReflexTex.DecodeExactRgba(c.ReadAsset(l.sphericalLightMap, "texture"), out int w, out int h);
            var dirs = c.LightDirections();
            double se = 0, sunErr = 0; int n = 0; double maxErr = 0;
            for (int y = 0; y < h; y++)
                for (int x = 0; x < w; x++)
                {
                    float X = 2f * (x + 0.5f) / w - 1f, Z = 1f - 2f * (y + 0.5f) / h; float r2 = X * X + Z * Z;
                    if (r2 >= 0.9f) continue;
                    var N = new Vector3(X, Mathf.Sqrt(1f - r2), Z).normalized;
                    var rgb = Vector3.zero;
                    for (int i = 0; i < 4; i++) rgb += Mathf.Clamp01(Vector3.Dot(N, dirs[i])) * l.lightColors[i];
                    for (int k = 0; k < 3; k++) { double d = Mathf.Clamp01(rgb[k]) - px[(y * w + x) * 4 + k] / 255.0; se += d * d; maxErr = Math.Max(maxErr, Math.Abs(d)); n++; }
                    sunErr = Math.Max(sunErr, Math.Abs(Mathf.Clamp01(Vector3.Dot(N, l.sunDirection)) - px[(y * w + x) * 4 + 3] / 255.0));
                }
            return $"  light rig vs {l.sphericalLightMap} ({w}x{h}, {n} values): rmse {Math.Sqrt(se / n):F4}, max {maxErr:F4}; sun alpha max err {sunErr:F4}; directions " +
                   string.Join(" ", dirs.Select(d => d.ToString("F3"))) + "\n";
        }

        /// Instance and material counts per pixel shader (which shaders the scenery actually needs).
        public static string ShaderUsage(ReflexLevelContent c)
        {
            var sb = new StringBuilder();
            var perShader = new Dictionary<string, (int mats, int insts, int tris)>();
            foreach (var inst in c.instances)
            {
                var md = c.sceneModels[inst.model];
                for (int s = 0; s < inst.materials.Length; s++)
                {
                    string ps = c.sceneMaterials.TryGetValue(inst.materials[s], out var lm) ? lm.pixelShader : "(missing)";
                    var v = perShader.TryGetValue(ps ?? "(none)", out var cur) ? cur : (mats: 0, insts: 0, tris: 0);
                    perShader[ps ?? "(none)"] = (v.mats, v.insts + 1, v.tris + (s < md.triangles.Count ? md.triangles[s].Length / 3 : 0));
                }
            }
            foreach (var lm in c.sceneMaterials.Values)
            {
                string ps = lm.pixelShader ?? "(none)";
                var v = perShader.TryGetValue(ps, out var cur) ? cur : (mats: 0, insts: 0, tris: 0);
                perShader[ps] = (v.mats + 1, v.insts, v.tris);
            }
            foreach (var kv in perShader.OrderByDescending(k => k.Value.tris))
                sb.AppendLine($"  {kv.Key}: {kv.Value.mats} materials, {kv.Value.insts} submesh instances, {kv.Value.tris} triangles");
            return sb.ToString();
        }
        static float F(JToken t) => (float)t;
        static float[] Floats(JToken t) => ((JArray)t).Select(F).ToArray();

        static void Compare(Stat s, Vector3 a, JToken b, double tol, string where)
        {
            s.Add(Math.Abs(a.x - F(b[0])), tol, where); s.Add(Math.Abs(a.y - F(b[1])), tol, where); s.Add(Math.Abs(a.z - F(b[2])), tol, where);
        }

        static int[] Tri(JToken tris) => tris.SelectMany(t => t.Select(v => (int)v)).ToArray();

        static byte[] LoadPng(string path, out int w, out int h)
        {
            var t = new Texture2D(2, 2, TextureFormat.RGBA32, false, true);
            t.LoadImage(File.ReadAllBytes(path), false);
            w = t.width; h = t.height;
            // convert whatever LoadImage produced to RGBA32 explicitly
            var px = t.GetPixels32();
            var raw = new byte[w * h * 4];
            for (int i = 0; i < px.Length; i++) { raw[i * 4] = px[i].r; raw[i * 4 + 1] = px[i].g; raw[i * 4 + 2] = px[i].b; raw[i * 4 + 3] = px[i].a; }
            UnityEngine.Object.DestroyImmediate(t);
            return raw;   // Unity row order (bottom first)
        }

        /// Compares the exact CPU decode of a texture resource with a PNG exported by Python. Unity PNG rows are bottom first.
        static void CompareTexture(ReflexLevelContent c, Stat rgb, Stat alpha, string name, string png, string label)
        {
            if (!File.Exists(png)) return;
            var raw = c.ReadAsset(name, "texture");
            var mine = ReflexTex.DecodeExactRgba(raw, out int w, out int h);   // D3D rows (top first)
            var ref_ = LoadPng(png, out int pw, out int ph);
            if (pw != w || ph != h) { rgb.Add(1e9, 0, $"{label}: size {w}x{h} vs {pw}x{ph}"); return; }
            int fmt = ReflexTex.D3dFormat(raw);
            for (int y = 0; y < h; y++)
                for (int x = 0; x < w; x++)
                {
                    int a = (y * w + x) * 4, b = ((h - 1 - y) * w + x) * 4;
                    for (int k = 0; k < 3; k++) rgb.Add(Math.Abs(mine[a + k] - ref_[b + k]), 0, $"{label} ({x},{y}) c{k}");
                    alpha.Add(Math.Abs(mine[a + 3] - ref_[b + 3]), 0, $"{label} ({x},{y}) a {mine[a + 3]} vs {ref_[b + 3]} fmt {fmt}");
                }
        }

